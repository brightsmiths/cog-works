/// Per-model configuration used to select and account for LLM API calls.
///
/// The `LlmGateway` (in `nodes`) selects a `ModelConfig` based on node
/// configuration. The `StructuredResponse` echoes back the token counts
/// measured against this config.
///
/// See `docs/spec/interfaces/domain-traits.md` §ModelConfig.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ModelConfig {
    /// Provider-specific model identifier
    /// (e.g. `"claude-3-5-sonnet-20241022"`, `"gpt-4o"`).
    pub model_id: String,
    /// Maximum number of tokens the model's context window can hold
    /// (prompt + completion combined for some providers).
    pub context_window_size: u64,
    /// Maximum completion tokens the provider will return in one call.
    pub max_output_tokens: u64,
    /// Cost in USD per input token (prompt tokens).
    ///
    /// Used for pre-call budget estimation.
    pub input_cost_per_token: f64,
    /// Cost in USD per output token (completion tokens).
    ///
    /// Used for post-call cost accounting.
    pub output_cost_per_token: f64,
}

// ---------------------------------------------------------------------------

/// The validated completion returned by [`LlmProvider::complete`].
///
/// The `content` field has been checked against the [`OutputSchema`] before
/// the response is returned to the caller. If schema validation failed,
/// [`LlmError::SchemaValidationFailed`] is returned instead — this struct
/// is only constructed on success.
///
/// See `docs/spec/interfaces/domain-traits.md` §StructuredResponse.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct StructuredResponse {
    /// The completion content, validated against the requested `OutputSchema`.
    content: serde_json::Value,
    /// Number of tokens in the prompt (input tokens billed by the provider).
    input_tokens: TokenCount,
    /// Number of tokens in the completion (output tokens billed by the provider).
    output_tokens: TokenCount,
    /// Wall-clock latency of the API call in milliseconds.
    latency_ms: u64,
}

impl StructuredResponse {
    /// Creates a new validated response.
    ///
    /// [`LlmProvider`] implementations should return
    /// [`LlmError::SchemaValidationFailed`] instead of constructing a response
    /// when validation fails.
    #[must_use]
    pub fn new(
        content: serde_json::Value,
        input_tokens: TokenCount,
        output_tokens: TokenCount,
        latency_ms: u64,
    ) -> Self {
        Self {
            content,
            input_tokens,
            output_tokens,
            latency_ms,
        }
    }

    /// Returns the validated completion content.
    pub fn content(&self) -> &serde_json::Value {
        &self.content
    }

    /// Returns the number of prompt (input) tokens billed by the provider.
    pub fn input_tokens(&self) -> TokenCount {
        self.input_tokens
    }

    /// Returns the number of completion (output) tokens billed by the provider.
    pub fn output_tokens(&self) -> TokenCount {
        self.output_tokens
    }

    /// Returns the wall-clock latency of the API call in milliseconds.
    pub fn latency_ms(&self) -> u64 {
        self.latency_ms
    }
}

// ─── LLM error type ─────────────────────────────────────────────────────────

/// Errors returned by [`LlmProvider::complete`].
///
/// See `docs/spec/interfaces/domain-traits.md` §LlmError.
#[derive(Debug, Error, Serialize, Deserialize)]
pub enum LlmError {
    /// The provider is enforcing a rate limit.
    ///
    /// The `retry_after` duration is derived from `Retry-After` or
    /// `x-ratelimit-reset` response headers when available.
    #[error("LLM provider rate-limited; retry after {retry_after:?}")]
    RateLimited {
        /// Minimum duration to wait before retrying, if known.
        retry_after: Option<std::time::Duration>,
    },

    /// The provider returned a non-2xx HTTP status code.
    #[error("LLM API error (HTTP {status_code}): {message}")]
    ApiError {
        /// HTTP status code from the provider response.
        status_code: u16,
        /// Error message from the provider response body.
        message: String,
    },

    /// The completion was returned but did not conform to the requested
    /// `OutputSchema`.
    ///
    /// The raw completion is included for audit trail and debug purposes.
    /// Callers must not use the `content` field for domain logic — they
    /// should treat this as a failure and apply their retry budget.
    #[error("LLM completion failed schema validation: {violations:?}")]
    SchemaValidationFailed {
        /// Raw completion content that failed validation.
        content: serde_json::Value,
        /// Human-readable descriptions of each schema violation.
        violations: Vec<String>,
    },

    /// A transport-level error occurred before the provider returned a response.
    #[error("LLM provider network error: {message}")]
    NetworkError {
        /// Description of the network failure.
        message: String,
    },

    /// The assembled prompt exceeds the model's context window.
    ///
    /// Callers should reduce the context package (lower summary levels or
    /// fewer items) before retrying.
    #[error("Prompt context window exceeded: requested {requested} tokens, model limit is {limit}")]
    ContextWindowExceeded {
        /// Number of tokens in the assembled prompt.
        requested: TokenCount,
        /// Maximum tokens the model accepts.
        limit: TokenCount,
    },
}

impl LlmError {
    /// Whether this error is likely transient and safe to retry.
    pub fn retry_policy(&self) -> crate::errors::RetryPolicy {
        use crate::errors::RetryPolicy;
        match self {
            Self::RateLimited { retry_after } => RetryPolicy::Retryable {
                after: *retry_after,
            },
            Self::ApiError { status_code, .. } if *status_code >= 500 => {
                RetryPolicy::Retryable { after: None }
            }
            Self::NetworkError { .. } => RetryPolicy::Retryable { after: None },
            // HTTP 408 (Request Timeout) falls through to ApiError and is
            // treated as NonRetryable here. The LlmGateway in `nodes` applies
            // its own retry budget; revisit if 408s prove common in practice.
            Self::ApiError { .. }
            | Self::SchemaValidationFailed { .. }
            | Self::ContextWindowExceeded { .. } => RetryPolicy::NonRetryable,
        }
    }
}

// ─── LLM provider trait ─────────────────────────────────────────────────────

/// Port trait for LLM API providers.
///
/// This trait abstracts over the concrete HTTP API of each LLM provider.
/// The `LlmGateway` in the `nodes` crate wraps this trait with constitutional
/// prompt assembly, rate-limit management, and schema validation retry logic.
///
/// ## Implementors
///
/// - `llm::AnthropicProvider` — Anthropic Messages API (Claude family)
/// - Additional providers are added as new `impl` blocks in the `llm` crate
///   without any changes to `pipeline`.
///
/// ## Constitutional Rules
///
/// The `system_prompt` parameter MUST contain the constitutional rules text.
/// The `LlmGateway` ensures this; direct callers of `LlmProvider::complete`
/// are responsible for passing a constitutionally-safe system prompt.
///
/// ## Architectural Layer
///
/// Trait defined in `pipeline`; implemented in the `llm` infrastructure crate.
///
/// See `docs/spec/interfaces/domain-traits.md` §LlmProvider.
#[async_trait]
pub trait LlmProvider: Send + Sync {
    /// Sends a chat-style completion request and returns the structured
    /// response.
    ///
    /// # Arguments
    /// - `system_prompt` — the system-role instruction text. This MUST include
    ///   the constitutional rules text (see `docs/spec/security.md`).
    /// - `messages` — the ordered message sequence (user/assistant turns).
    /// - `schema` — JSON Schema the completion must conform to.
    /// - `model` — model selection and cost configuration.
    ///
    /// # Returns
    /// [`StructuredResponse`] with validated `content`, token counts, latency.
    ///
    /// # Errors
    /// - [`LlmError::RateLimited`] — provider rate limit hit; retry after delay.
    /// - [`LlmError::ApiError`] — provider returned a non-2xx response.
    /// - [`LlmError::SchemaValidationFailed`] — completion did not match schema.
    /// - [`LlmError::NetworkError`] — transport failure before response received.
    /// - [`LlmError::ContextWindowExceeded`] — prompt too large for the model.
    ///
    /// # Security
    ///
    /// Never log `messages` content — it may contain proprietary code,
    /// issue descriptions, or other sensitive data. Log only token counts,
    /// model ID, and latency.
    async fn complete(
        &self,
        system_prompt: &str,
        messages: &[ChatMessage],
        schema: &OutputSchema,
        model: &ModelConfig,
    ) -> Result<StructuredResponse, LlmError>;
}

// ─── Progressive tool discovery ──────────────────────────────────────────────

/// A single entry in the compact tool index.
///
/// Used by LLM nodes during progressive tool discovery: the node first receives
/// a [`CompactToolIndex`] and searches for a fitting tool before requesting the
/// full tool definition.
///
/// See `docs/spec/interfaces/advanced-features.md` §ToolIndexEntry.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ToolIndexEntry {
    /// The tool's canonical name.
    pub tool_name: ToolName,

    /// One-line human-readable description of the tool.
    ///
    /// Currently populated as an empty string when built via
    /// [`build_compact_index`]; description enrichment is expected to occur
    /// in the `nodes` crate when the index is assembled for LLM consumption.
    pub description: String,

    /// `true` if this entry represents a composite skill rather than a raw
    /// tool call.
    ///
    /// Skills are ranked before raw tools in [`CompactToolIndex::entries`].
    pub is_skill: bool,
}

// ---------------------------------------------------------------------------

/// An ordered, skill-first list of all available tools and skills.
///
/// Used as the first response to an LLM agent querying which tools exist.
/// The agent searches the compact index to find a tool of interest, then
/// requests its full definition before invoking it.
///
/// ## Ordering
///
/// Skills appear before raw tools. Within each group, entries are sorted
/// alphabetically by `tool_name`.
///
/// See `docs/spec/interfaces/advanced-features.md` §CompactToolIndex.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CompactToolIndex {
    /// All available tools and skills, skills ranked first then alphabetical.
    pub entries: Vec<ToolIndexEntry>,
}

// ---------------------------------------------------------------------------

/// Constructs a compact tool index from a list of available tool names and
/// their profile metadata.
///
/// # Arguments
///
/// * `tool_list` — canonical names of tools that may be invoked.
/// * `profiles` — tool profiles used to determine which tools are skills.
///
/// # Returns
///
/// A [`CompactToolIndex`] with skills sorted before raw tools; within each
/// group, alphabetical by `tool_name`. [`ToolIndexEntry::description`] is
/// populated as an empty string.
///
/// See `docs/spec/interfaces/advanced-features.md` §build_compact_index.
pub fn build_compact_index(
    tool_list: &[ToolName],
    profiles: &[crate::knowledge::ToolProfile],
) -> CompactToolIndex {
    let skill_names: std::collections::HashSet<&str> = profiles
        .iter()
        .flat_map(|profile| profile.allowed_skills.iter())
        .map(SkillName::as_str)
        .collect();

    let mut entries: Vec<ToolIndexEntry> = tool_list
        .iter()
        .map(|tool_name| {
            let is_skill = skill_names.contains(tool_name.as_str());
            ToolIndexEntry {
                tool_name: tool_name.clone(),
                description: String::new(),
                is_skill,
            }
        })
        .collect();

    entries.sort_by(|a, b| {
        (!a.is_skill, a.tool_name.as_str()).cmp(&(!b.is_skill, b.tool_name.as_str()))
    });

    CompactToolIndex { entries }
}

// ---------------------------------------------------------------------------

/// Returns all entries in a [`CompactToolIndex`] whose name or description
/// contains `query` as a case-insensitive substring.
///
/// Matching entries are returned in the same order they appear in
/// `index.entries` (skills before raw tools, alphabetical within each group).
///
/// # Arguments
///
/// * `index` — the compact tool index to search.
/// * `query` — case-insensitive substring to look for in `tool_name` and
///   `description`.
///
/// See `docs/spec/interfaces/advanced-features.md` §search_tools.
pub fn search_tools(index: &CompactToolIndex, query: &str) -> Vec<ToolIndexEntry> {
    let query = query.to_lowercase();
    index
        .entries
        .iter()
        .filter(|entry| {
            entry.tool_name.as_str().to_lowercase().contains(&query)
                || entry.description.to_lowercase().contains(&query)
        })
        .cloned()
        .collect()
}

// ─── Skill validation ────────────────────────────────────────────────────────

/// Lifecycle state of a skill; governs whether the skill may be invoked.
///
/// See `docs/spec/interfaces/advanced-features.md` §SkillLifecycle.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum SkillLifecycle {
    /// Under review, not yet approved for use. Not invocable.
    Proposed,
    /// Review complete but not yet activated. Not invocable.
    Reviewed,
    /// Fully approved. Invocable.
    Active,
    /// Deprecated in favour of `alternative`. Not invocable.
    Deprecated {
        /// The replacement skill that callers should use instead.
        alternative: SkillName,
    },
    /// Permanently removed. Not invocable.
    Retired,
}

impl SkillLifecycle {
    /// Returns `true` if the skill may be invoked (only [`Active`](Self::Active)
    /// lifecycles are invocable).
    #[must_use]
    pub fn is_invocable(&self) -> bool {
        matches!(self, Self::Active)
    }
}

impl std::fmt::Display for SkillLifecycle {
    /// Writes the bare variant identifier (e.g. `"Proposed"`, `"Deprecated"`
    /// — without the `Deprecated` variant's `alternative` field contents).
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Proposed => write!(f, "Proposed"),
            Self::Reviewed => write!(f, "Reviewed"),
            Self::Active => write!(f, "Active"),
            Self::Deprecated { .. } => write!(f, "Deprecated"),
            Self::Retired => write!(f, "Retired"),
        }
    }
}


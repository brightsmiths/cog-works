// ─── LLM call types ─────────────────────────────────────────────────────────

/// Role of a message in a chat-style LLM conversation.
///
/// See `docs/spec/interfaces/domain-traits.md` §ChatRole.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum ChatRole {
    /// Instructions and context provided by CogWorks (the system operator).
    System,
    /// Content submitted as if from the end user (prompt and context).
    User,
    /// Content generated by the LLM in a prior turn (used for few-shot examples
    /// or multi-turn flows).
    Assistant,
}

// ---------------------------------------------------------------------------

/// A single message in a chat-style conversation sent to the LLM provider.
///
/// `ChatMessage` is intentionally immutable: once constructed the role and
/// content cannot be changed. Mutation after construction would allow callers
/// to bypass the injection guard that validates content before the message is
/// assembled into a prompt.
///
/// Use the convenience constructors [`ChatMessage::system`],
/// [`ChatMessage::user`], and [`ChatMessage::assistant`] to build messages.
///
/// See `docs/spec/interfaces/domain-traits.md` §ChatMessage.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ChatMessage {
    /// The role of the message sender.
    role: ChatRole,
    /// The text content of the message.
    ///
    /// Must not be empty. Constitutional system prompts are included in
    /// the `System` role message; injecting instructions into `User` role
    /// content is detected by the injection guard.
    content: String,
}

impl ChatMessage {
    /// Creates a system-role message.
    ///
    /// Returns `None` if `content` is empty.
    #[must_use]
    pub fn system(content: impl Into<String>) -> Option<Self> {
        let content = content.into();
        if content.is_empty() {
            return None;
        }
        Some(Self {
            role: ChatRole::System,
            content,
        })
    }

    /// Creates a user-role message.
    ///
    /// Returns `None` if `content` is empty.
    #[must_use]
    pub fn user(content: impl Into<String>) -> Option<Self> {
        let content = content.into();
        if content.is_empty() {
            return None;
        }
        Some(Self {
            role: ChatRole::User,
            content,
        })
    }

    /// Creates an assistant-role message (for few-shot examples).
    ///
    /// Returns `None` if `content` is empty.
    #[must_use]
    pub fn assistant(content: impl Into<String>) -> Option<Self> {
        let content = content.into();
        if content.is_empty() {
            return None;
        }
        Some(Self {
            role: ChatRole::Assistant,
            content,
        })
    }

    /// Returns the role of this message.
    pub fn role(&self) -> &ChatRole {
        &self.role
    }

    /// Returns the text content of this message.
    pub fn content(&self) -> &str {
        &self.content
    }
}


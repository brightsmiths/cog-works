//! LLM provider trait and LLM call types.
//!
//! This module defines the [`LlmProvider`] port trait and the supporting
//! data types for LLM API calls:
//!
//! - [`ChatMessage`] / [`ChatRole`] — the message sequence passed to the API.
//! - [`ModelConfig`] — per-model configuration (context window, costs, etc.).
//! - [`OutputSchema`] — JSON Schema describing the expected completion structure.
//! - [`StructuredResponse`] — validated completion with token accounting.
//! - [`LlmError`] — all failure modes for LLM provider calls.
//!
//! It also contains progressive tool discovery and skill validation types:
//!
//! - [`ToolIndexEntry`] / [`CompactToolIndex`] — compact index for LLM tool discovery.
//! - [`build_compact_index`] / [`search_tools`] — index construction and search.
//! - [`SkillLifecycle`] / [`SkillManifest`] / [`SkillInvocation`] — skill metadata.
//! - [`ValidatedSkillInvocation`] — opaque validated skill invocation token.
//! - [`SkillError`] — skill validation error variants.
//! - [`validate_skill_invocation`] — skill lifecycle, profile, and schema validation.
//!
//! ## LLM Call Flow
//!
//! The `nodes` crate's `LlmGateway` orchestrates constitutional prompt wrapping
//! and rate-limit management before delegating to this trait. The trait
//! itself is the raw provider interface — it does not enforce constitutional
//! rules.
//!
//! ```text
//! nodes::LlmGateway::call(ConstitutionallyWrappedPrompt, context, schema, model)
//!     └── pipeline::LlmProvider::complete(system, messages, schema, model)
//!             └── llm::AnthropicProvider  (or other impl)
//! ```
//!
//! ## Multi-Provider Support
//!
//! Adding a provider is additive: create a new `impl LlmProvider` in the `llm`
//! crate. No changes to `pipeline` are required.
//!
//! ## Architectural Layer
//!
//! Trait defined in `pipeline` (port layer); implemented in the `llm`
//! infrastructure crate (Anthropic, OpenAI, etc.).
//!
//! ## Specification
//!
//! See `docs/spec/interfaces/domain-traits.md` §LLM Provider Trait for the
//! full contract.
//! See `docs/spec/interfaces/advanced-features.md` for tool discovery and
//! skill validation contracts.

